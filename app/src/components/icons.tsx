export type IconName = keyof typeof Icons;

export function Icon({
  name,
  size = 16,
  weight = "duotone",
  className,
}: {
  name: IconName;
  size?: number;
  weight?: IconWeight;
  className?: string;
}) {
  const Cmp = Icons[name];
  return <Cmp size={size} weight={weight} className={className} />;
}
